# Regenerates frontend/assets/icons.svg.
#
# The app uses the Material Symbols icon set (the same one the original
# Tailwind build imported), but it needs about thirty glyphs, not the whole
# 3.8 MB variable font. This pulls the exact paths for those thirty and packs
# them into one small sprite, so the icons stay offline and byte-identical to
# the set they came from.
#
# Usage:  pwsh -File scripts/fetch-icons.ps1

param(
    [string]$Version = '0.28.0',
    [string]$Out = "$PSScriptRoot/../frontend/assets/icons.svg"
)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$icons = @(
    # navigation
    'dashboard', 'inventory_2', 'search', 'update', 'cleaning_services',
    'hub', 'history', 'terminal', 'health_and_safety', 'settings',
    # controls and states
    'refresh', 'add', 'close', 'keyboard_arrow_down', 'check', 'warning',
    'error', 'info', 'light_mode', 'dark_mode', 'folder_open', 'open_in_new',
    'delete', 'download', 'sync', 'arrow_upward', 'link', 'progress_activity'
)

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('<!-- Generated by scripts/fetch-icons.ps1 from @material-symbols/svg-400. Do not edit by hand. -->')
$lines.Add('<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">')

$missing = 0
foreach ($icon in $icons) {
    $url = "https://cdn.jsdelivr.net/npm/@material-symbols/svg-400@$Version/outlined/$icon.svg"
    try {
        $body = (Invoke-WebRequest -Uri $url -UseBasicParsing).Content
    } catch {
        Write-Warning "could not fetch $icon"
        $missing++
        continue
    }
    $match = [regex]::Match($body, 'd="([^"]+)"')
    if (-not $match.Success) {
        Write-Warning "no path data in $icon"
        $missing++
        continue
    }
    $lines.Add("  <symbol id=`"i-$icon`" viewBox=`"0 -960 960 960`"><path d=`"$($match.Groups[1].Value)`"/></symbol>")
}

$lines.Add('</svg>')

$resolved = [System.IO.Path]::GetFullPath($Out)
New-Item -ItemType Directory -Force -Path ([System.IO.Path]::GetDirectoryName($resolved)) | Out-Null
[System.IO.File]::WriteAllLines($resolved, $lines, [System.Text.UTF8Encoding]::new($false))

Write-Host "wrote $resolved ($((Get-Item $resolved).Length) bytes, $($icons.Count - $missing) icons)"
if ($missing -gt 0) { exit 1 }
